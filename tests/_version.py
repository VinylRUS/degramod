"""Сравнение `APP_VERSION` как кортежа чисел, а не строки.

Зачем. Полтора десятка файлов сюиты проверяют `APP_VERSION >= "vX.Y.Z"`, и до
v4.9.0 это работало, потому что все минорные версии были однозначными —
строковое и числовое сравнение совпадали. На v4.10.0 разошлись:
`"v4.10.0" < "v4.7.19"` лексикографически (символ `"1"` меньше `"7"`), хотя
4.10.0 старше. Так упали разом 16 файлов при бампе версии в Task 12.

`ver()` — общая точка починки: парсит `"v4.10.0"` → `(4, 10, 0)`, и
`assertGreaterEqual` дальше сравнивает кортежи по элементам, как задумано.
"""
from __future__ import annotations


def ver(s: str) -> tuple[int, ...]:
    """`"v4.10.0"` → `(4, 10, 0)`. Ведущая `v` не обязательна."""
    return tuple(int(p) for p in s.lstrip("v").split("."))
